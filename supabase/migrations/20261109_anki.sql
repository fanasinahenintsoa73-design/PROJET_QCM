-- ------------------------------------------------------------------
-- Choix des 5 chapitres Anki
-- ------------------------------------------------------------------
create or replace function public.anki_select_chapters(p_chapter_ids text[])
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
  v_type text;
  v_status text;
  v_expires timestamptz;
  v_ids text[];
begin
  select t.code, t.type, t.status, t.expires_at
    into v_code, v_type, v_status, v_expires
  from public.tickets t
  where t.user_id = auth.uid();

  if v_code is null then
    raise exception 'Ticket introuvable.';
  end if;

  if v_type <> 'anki' then
    raise exception 'Ce ticket n’est pas un ticket Anki.';
  end if;

  if v_status = 'suspended' then
    raise exception 'Ce ticket est suspendu.';
  end if;

  if v_expires is not null and v_expires < now() then
    raise exception 'Ticket Anki expiré.';
  end if;

  if exists (select 1 from public.anki_ticket_chapters where ticket_code = v_code) then
    raise exception 'Les chapitres sont déjà choisis pour ce ticket.';
  end if;

  select array_agg(distinct x)
    into v_ids
  from unnest(p_chapter_ids) x
  where x is not null and x <> '';

  if v_ids is null or cardinality(v_ids) = 0 then
    raise exception 'Choisis au moins un chapitre.';
  end if;

  if cardinality(v_ids) > 5 then
    raise exception 'Choisis 5 chapitres maximum.';
  end if;

  insert into public.anki_ticket_chapters (ticket_code, chapter_id, position)
  select v_code, x, row_number() over ()
  from unnest(v_ids) x;

  insert into public.anki_chapter_progress (ticket_code, chapter_id)
  select v_code, x
  from unnest(v_ids) x;
end;
$$;

revoke all on function public.anki_select_chapters(text[]) from public;
grant execute on function public.anki_select_chapters(text[]) to authenticated;

-- ------------------------------------------------------------------
-- Chapitres et progression du ticket Anki connecté
-- ------------------------------------------------------------------
create or replace function public.anki_chapters()
returns table (
  chapter_id text,
  level integer,
  completed_blocks integer,
  completed_at timestamptz,
  total_questions integer,
  answered_questions integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
begin
  select t.code into v_code from public.tickets t where t.user_id = auth.uid();
  if v_code is null then
    return;
  end if;

  return query
    select c.chapter_id, p.level, p.completed_blocks, p.completed_at,
      (select count(*)::integer
        from public.questions q
        join public.subjects s on s.id = q.subject_id
        where s.chapter_id = c.chapter_id
          and s.archived = false
          and cardinality(q.correct_answers) = 1) as total_questions,
      (select count(*)::integer
        from public.anki_history h
        where h.ticket_code = c.ticket_code and h.chapter_id = c.chapter_id) as answered_questions
    from public.anki_ticket_chapters c
    join public.anki_chapter_progress p
      on p.ticket_code = c.ticket_code and p.chapter_id = c.chapter_id
    where c.ticket_code = v_code
    order by c.position;
end;
$$;

revoke all on function public.anki_chapters() from public;
grant execute on function public.anki_chapters() to authenticated;

-- ------------------------------------------------------------------
-- 5 questions aléatoires non encore répondues du chapitre
-- ------------------------------------------------------------------
create or replace function public.anki_next_questions(p_chapter_id text)
returns table (
  id uuid,
  subject_id uuid,
  number integer,
  matiere text,
  statement text,
  options jsonb,
  correct_answers text[],
  explanation text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
  v_type text;
  v_status text;
  v_expires timestamptz;
begin
  select t.code, t.type, t.status, t.expires_at
    into v_code, v_type, v_status, v_expires
  from public.tickets t
  where t.user_id = auth.uid();

  if v_code is null or v_type <> 'anki' then
    raise exception 'Ticket Anki introuvable.';
  end if;

  if v_status = 'suspended' then
    raise exception 'Ce ticket est suspendu.';
  end if;

  if v_expires is not null and v_expires < now() then
    raise exception 'Ticket Anki expiré.';
  end if;

  if not exists (
    select 1 from public.anki_ticket_chapters c
    where c.ticket_code = v_code and c.chapter_id = p_chapter_id
  ) then
    raise exception 'Chapitre non choisi pour ce ticket.';
  end if;

  return query
    select q.id, q.subject_id, q.number, q.matiere, q.statement, q.options, q.correct_answers, q.explanation
    from public.questions q
    join public.subjects s on s.id = q.subject_id
    where s.chapter_id = p_chapter_id
      and s.archived = false
      and cardinality(q.correct_answers) = 1
      and q.id not in (
        select h.question_id from public.anki_history h
        where h.ticket_code = v_code and h.chapter_id = p_chapter_id
      )
    order by random()
    limit 5;
end;
$$;

revoke all on function public.anki_next_questions(text) from public;
grant execute on function public.anki_next_questions(text) to authenticated;

-- ------------------------------------------------------------------
-- Enregistrement d'une réponse Anki + progression
-- ------------------------------------------------------------------
create or replace function public.anki_record_answer(
  p_chapter_id text,
  p_question_id uuid,
  p_given_answers text[],
  p_status text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
  v_type text;
  v_status text;
  v_expires timestamptz;
  v_statement text;
  v_correct text[];
  v_explanation text;
  v_count integer;
  v_level integer;
  v_blocks integer;
  v_completed boolean;
begin
  if p_status not in ('correct', 'wrong', 'revealed', 'skipped') then
    raise exception 'Statut de réponse invalide.';
  end if;

  select t.code, t.type, t.status, t.expires_at
    into v_code, v_type, v_status, v_expires
  from public.tickets t
  where t.user_id = auth.uid();

  if v_code is null or v_type <> 'anki' then
    raise exception 'Ticket Anki introuvable.';
  end if;

  if v_status = 'suspended' then
    raise exception 'Ce ticket est suspendu.';
  end if;

  if v_expires is not null and v_expires < now() then
    raise exception 'Ticket Anki expiré.';
  end if;

  if not exists (
    select 1 from public.anki_ticket_chapters c
    where c.ticket_code = v_code and c.chapter_id = p_chapter_id
  ) then
    raise exception 'Chapitre non choisi pour ce ticket.';
  end if;

  select q.statement, q.correct_answers, coalesce(q.explanation, '')
    into v_statement, v_correct, v_explanation
  from public.questions q
  where q.id = p_question_id;

  if v_statement is null then
    raise exception 'Question introuvable.';
  end if;

  insert into public.anki_history (
    ticket_code, chapter_id, question_id, question_statement,
    given_answers, correct_answers, explanation, status
  ) values (
    v_code, p_chapter_id, p_question_id, v_statement,
    coalesce(p_given_answers, '{}'), v_correct, v_explanation, p_status
  )
  on conflict (ticket_code, chapter_id, question_id) do nothing;

  select count(*)::integer into v_count
  from public.anki_history h
  where h.ticket_code = v_code and h.chapter_id = p_chapter_id;

  v_level := 1 + floor(v_count / 5.0)::integer;
  v_blocks := floor(v_count / 5.0)::integer;

  select not exists (
    select 1
    from public.questions q
    join public.subjects s on s.id = q.subject_id
    where s.chapter_id = p_chapter_id
      and s.archived = false
      and cardinality(q.correct_answers) = 1
      and q.id not in (
        select h.question_id from public.anki_history h
        where h.ticket_code = v_code and h.chapter_id = p_chapter_id
      )
  ) into v_completed;

  update public.anki_chapter_progress p
    set level = v_level,
        completed_blocks = v_blocks,
        completed_at = case
          when v_completed then coalesce(p.completed_at, now())
          else p.completed_at
        end
  where p.ticket_code = v_code and p.chapter_id = p_chapter_id;

  return jsonb_build_object(
    'level', v_level,
    'completedBlocks', v_blocks,
    'completed', v_completed
  );
end;
$$;

revoke all on function public.anki_record_answer(text, uuid, text[], text) from public;
grant execute on function public.anki_record_answer(text, uuid, text[], text) to authenticated;

-- ------------------------------------------------------------------
-- Historique Anki du ticket connecté
-- ------------------------------------------------------------------
create or replace function public.anki_get_history()
returns table (
  id bigint,
  chapter_id text,
  question_id uuid,
  statement text,
  given_answers text[],
  correct_answers text[],
  explanation text,
  status text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
begin
  select t.code into v_code from public.tickets t where t.user_id = auth.uid();
  if v_code is null then
    return;
  end if;

  return query
    select h.id, h.chapter_id, h.question_id, h.question_statement,
      h.given_answers, h.correct_answers, h.explanation, h.status, h.created_at
    from public.anki_history h
    where h.ticket_code = v_code
    order by h.created_at desc
    limit 100;
end;
$$;

revoke all on function public.anki_get_history() from public;
grant execute on function public.anki_get_history() to authenticated;
