-- ============================================================
-- MEDQCM : mode Anki (tickets séparés, 5 chapitres, 1 mois)
-- ============================================================

-- ------------------------------------------------------------------
-- Colonnes de type et d'expiration sur les tickets
-- ------------------------------------------------------------------
alter table public.tickets
  add column if not exists type text not null default 'series';

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'tickets_type_check' and conrelid = 'public.tickets'::regclass
  ) then
    alter table public.tickets
      add constraint tickets_type_check check (type in ('series', 'anki'));
  end if;
end $$;

alter table public.tickets
  add column if not exists expires_at timestamptz;

-- ------------------------------------------------------------------
-- Chapitres choisis par l'étudiant (5 maximum)
-- ------------------------------------------------------------------
create table if not exists public.anki_ticket_chapters (
  ticket_code text not null references public.tickets (code) on delete cascade,
  chapter_id text not null,
  position integer not null default 1,
  created_at timestamptz not null default now(),
  primary key (ticket_code, chapter_id)
);

-- ------------------------------------------------------------------
-- Progression par chapitre (niveau, blocs de 5 terminés)
-- ------------------------------------------------------------------
create table if not exists public.anki_chapter_progress (
  ticket_code text not null,
  chapter_id text not null,
  level integer not null default 1,
  completed_blocks integer not null default 0,
  completed_at timestamptz,
  primary key (ticket_code, chapter_id),
  foreign key (ticket_code, chapter_id)
    references public.anki_ticket_chapters (ticket_code, chapter_id)
    on delete cascade
);

-- ------------------------------------------------------------------
-- Historique des réponses Anki (y compris révélées et ignorées)
-- ------------------------------------------------------------------
create table if not exists public.anki_history (
  id bigint generated by default as identity primary key,
  ticket_code text not null references public.tickets (code) on delete cascade,
  chapter_id text not null,
  question_id uuid not null,
  question_statement text not null,
  given_answers text[] not null default '{}',
  correct_answers text[] not null default '{}',
  explanation text not null default '',
  status text not null check (status in ('correct', 'wrong', 'revealed', 'skipped')),
  created_at timestamptz not null default now(),
  unique (ticket_code, chapter_id, question_id)
);

alter table public.anki_ticket_chapters enable row level security;
alter table public.anki_chapter_progress enable row level security;
alter table public.anki_history enable row level security;

-- ------------------------------------------------------------------
-- Génération typée : 30 séries (PACES) ou Anki (ANKI)
-- ------------------------------------------------------------------
create or replace function public.generate_tickets_typed(p_count integer, p_type text)
returns table (code text, secret text, type text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_start integer;
  v_num integer;
  v_code text;
  v_secret text;
  v_user_id uuid;
  v_email text;
  v_prefix text;
  v_expires timestamptz;
  i integer;
begin
  if not exists (
    select 1 from public.profiles where id = auth.uid() and role = 'professor'
  ) then
    raise exception 'Réservé au docteur.';
  end if;

  if p_type not in ('series', 'anki') then
    raise exception 'Type de ticket invalide.';
  end if;

  if p_count is null or p_count < 1 or p_count > 500 then
    raise exception 'Nombre de tickets invalide (1 à 500).';
  end if;

  v_prefix := case when p_type = 'anki' then 'ANKI' else 'PACES' end;
  v_expires := case when p_type = 'anki' then now() + interval '1 month' else null end;

  select coalesce(max(case
      when t.code ~ ('^' || v_prefix || '[0-9]+$')
        then substring(t.code from length(v_prefix) + 1)::integer
    end), 0) + 1
    into v_start
  from public.tickets t;

  for i in 0 .. p_count - 1 loop
    v_num := v_start + i;
    v_code := v_prefix || lpad(v_num::text, 4, '0');

    select string_agg(pick, '' order by rnd)
      into v_secret
    from (
      select substring('0123456789' from 1 + floor(random() * 10)::integer for 1) as pick, random() as rnd
        from generate_series(1, 6)
      union all
      select substring('ABCDEFGHIJKLMNOPQRSTUVWXYZ' from 1 + floor(random() * 26)::integer for 1) as pick, random() as rnd
        from generate_series(1, 3)
    ) shuffled;

    v_user_id := gen_random_uuid();
    v_email := lower(v_code) || '@ticket.medqcm';

    insert into auth.users (
      instance_id, id, aud, role, email, encrypted_password,
      email_confirmed_at, raw_user_meta_data, raw_app_meta_data,
      confirmation_token, recovery_token, email_change_token_new, email_change,
      created_at, updated_at
    ) values (
      '00000000-0000-0000-0000-000000000000',
      v_user_id, 'authenticated', 'authenticated', v_email,
      extensions.crypt(v_secret, extensions.gen_salt('bf')),
      now(),
      jsonb_build_object('first_name', v_prefix, 'last_name', lpad(v_num::text, 4, '0')),
      '{"provider":"email","providers":["email"]}'::jsonb,
      '', '', '', '',
      now(), now()
    );

    insert into auth.identities (user_id, provider, provider_id, identity_data, created_at, updated_at)
    values (
      v_user_id, 'email', v_user_id::text,
      jsonb_build_object('sub', v_user_id::text, 'email', v_email, 'email_verified', true, 'phone_verified', false),
      now(), now()
    );

    update public.profiles
      set status = 'active', activated_at = now()
    where id = v_user_id;

    insert into public.subject_assignments (user_id, subject_id, started_at, expires_at)
    values (v_user_id, null, now(), now() + interval '100 years');

    insert into public.tickets (code, user_id, status, type, expires_at)
    values (v_code, v_user_id, 'available', p_type, v_expires);

    insert into public.ticket_secrets (code, secret)
    values (v_code, v_secret);

    code := v_code;
    secret := v_secret;
    type := p_type;
    return next;
  end loop;
end;
$$;

revoke all on function public.generate_tickets_typed(integer, text) from public;
grant execute on function public.generate_tickets_typed(integer, text) to authenticated;

-- ------------------------------------------------------------------
-- Liste des tickets : type, expiration, progression Anki
-- ------------------------------------------------------------------
drop function if exists public.list_tickets();

create function public.list_tickets()
returns table (
  code text,
  status text,
  series_used integer,
  created_at timestamptz,
  used_at timestamptz,
  last_login_at timestamptz,
  secret text,
  type text,
  expires_at timestamptz,
  anki_chapters integer,
  anki_completed integer
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1 from public.profiles where id = auth.uid() and role = 'professor'
  ) then
    raise exception 'Réservé au docteur.';
  end if;

  return query
    select t.code, t.status,
      (select count(*)::integer from public.attempts a where a.user_id = t.user_id) as series_used,
      t.created_at, t.used_at, t.last_login_at,
      (select s.secret from public.ticket_secrets s where s.code = t.code) as secret,
      t.type, t.expires_at,
      (select count(*)::integer from public.anki_ticket_chapters c where c.ticket_code = t.code) as anki_chapters,
      (select count(*)::integer from public.anki_chapter_progress p
        where p.ticket_code = t.code and p.completed_at is not null) as anki_completed
    from public.tickets t
    order by t.code;
end;
$$;

revoke all on function public.list_tickets() from public;
grant execute on function public.list_tickets() to authenticated;

